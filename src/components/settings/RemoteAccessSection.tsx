import { useCallback, useEffect, useState } from 'react';
import { apiGet, apiPost, getApiBase, getServerPort } from '../../lib/api';
import type { PollSettings } from '../../lib/types';
import Toggle from '../Toggle';
import { AdvancedSettings, SettingsSection } from './SettingsSection';
import { TEXT_INPUT as INPUT } from './styles';
import { useSettingsSave, useSettingToggle, type Flash } from './useSettingsSave';
import HelpTip, { HeadingWithHelp } from '../HelpTip';

const URL_CODE =
  'bg-bg-elevated text-accent rounded-lg px-4 py-2 text-sm font-mono flex-1 min-w-0 select-all overflow-hidden text-ellipsis whitespace-nowrap';
const COPY_BUTTON =
  'bg-bg-elevated text-text-primary font-sans text-sm px-4 py-2 rounded-lg hover:bg-bg-base transition-colors shrink-0';
const HINT = 'text-text-secondary text-xs font-sans';
const PRIMARY_BUTTON =
  'self-start bg-accent text-on-accent font-sans font-semibold text-sm px-5 py-2 rounded-lg hover:opacity-90 transition-opacity disabled:opacity-50';

const CONTROL_TEXT = {
  on: 'Battery control enabled for authenticated API clients',
  off: 'Battery control disabled for authenticated API clients',
  fail: 'Failed to update battery control permission',
};

function UrlRow({ url, onCopy, className = '' }: { url: string; onCopy: (url: string) => void; className?: string }) {
  return (
    <div className={`flex items-center gap-3 ${className}`}>
      <code className={URL_CODE}>{url}</code>
      <button onClick={() => onCopy(url)} className={COPY_BUTTON}>Copy</button>
    </div>
  );
}

/**
 * Settings → Remote / Mobile Network Access: the dashboard links to share,
 * the authenticated integration API (key, listener, control permission),
 * and the clients connected now.
 */
export default function RemoteAccessSection({
  id,
  flash,
  initial,
}: {
  id?: string;
  flash: Flash;
  initial: Partial<PollSettings>;
}) {
  const [lanIp, setLanIp] = useState<string | null>(null);
  const [clients, setClients] = useState<string[]>([]);
  // The key is generated by HEM and shown once; GET /api/settings returns
  // only whether one exists and its last four characters.
  const [generatedApiKey, setGeneratedApiKey] = useState<string | null>(null);
  const [apiKeyConfigured, setApiKeyConfigured] = useState(Boolean(initial.api_key_configured));
  const [apiKeyLast4, setApiKeyLast4] = useState(initial.api_key_last4 ?? '');
  // Blank bind = all interfaces; blank origins = no CORS headers.
  const [apiBindAddress, setApiBindAddress] = useState(initial.api_bind_address ?? '');
  const [apiAllowedOrigins, setApiAllowedOrigins] = useState((initial.api_allowed_origins ?? []).join(', '));
  const [apiPort, setApiPort] = useState<number | ''>(initial.api_port ?? 7338);
  const keySave = useSettingsSave(flash);
  const networkSave = useSettingsSave(flash);

  // Issue #301: the control permission saves the moment it's flipped, so
  // navigating away never leaves it unsaved. Turning it off does not stop
  // an action already accepted.
  const persistControl = useCallback((next: boolean) => apiPost('/api/settings', { api_control_enabled: next }), []);
  const [apiControlEnabled, setApiControlEnabled] = useSettingToggle(
    initial.api_control_enabled ?? false, persistControl, flash, CONTROL_TEXT,
  );

  useEffect(() => {
    let cancelled = false;
    apiGet<{ ok: boolean; lan_ip: string | null; clients: string[]; client_count: number }>('/api/status')
      .then((res) => {
        if (cancelled) return;
        if (res.lan_ip) setLanIp(res.lan_ip);
        if (res.clients) setClients(res.clients);
      })
      .catch((e: unknown) => console.warn('Failed to fetch status:', e));
    return () => { cancelled = true; };
  }, []);

  // The LAN address when known, else whatever this page was loaded from.
  const lanUrl = lanIp ? `http://${lanIp}:${getServerPort()}` : getApiBase();
  // `?RO` hides Control and Settings in the visitor's browser for that tab
  // (issue #114) — a convenience for family, not a security boundary.
  const lanReadOnlyUrl = `${lanUrl}?RO`;
  // A tiny glance view for a phone or Apple Watch browser; see INSTALL.md.
  const miniPageUrl = `${lanUrl}/mini`;

  const copyUrl = (text: string) => {
    if (navigator.clipboard && window.isSecureContext) {
      void navigator.clipboard.writeText(text).then(() => flash('URL copied!', true));
      return;
    }
    // Fallback for non-secure contexts (LAN HTTP).
    const ta = document.createElement('textarea');
    ta.value = text;
    ta.style.position = 'fixed';
    ta.style.opacity = '0';
    document.body.appendChild(ta);
    ta.select();
    try {
      document.execCommand('copy');
      flash('URL copied!', true);
    } catch {
      flash('Copy failed — please select and copy manually', false);
    }
    document.body.removeChild(ta);
  };

  // These messages stay up until the next one: the generate message tells
  // the user to copy a key they will never see again.
  const STICKY = { sticky: true };
  const portMissing = () => {
    if (apiPort !== '') return false;
    flash('API port cannot be blank', false, STICKY);
    return true;
  };

  // The port goes with key changes so "save key + port" keeps working.
  const handleApiKeyGenerate = () => {
    if (portMissing()) return;
    return keySave.run(async () => {
      const response = await apiPost<{ data?: { api_key?: string } }>('/api/settings', {
        api_key_generate: true,
        api_port: apiPort,
      });
      const secret = response.data?.api_key ?? '';
      if (!secret) throw new Error('Key generation did not return a secret');
      setGeneratedApiKey(secret);
      setApiKeyConfigured(true);
      setApiKeyLast4(secret.slice(-4));
      return 'New API key generated. Copy it now — it will not be shown again. Starting the API server or changing its port needs a restart.';
    }, 'Failed to generate API key', STICKY);
  };

  // The backend rebinds the live listener; if the bind fails it restores
  // the previous settings and returns the error.
  const handleApiNetworkSave = () => {
    if (portMissing()) return;
    return networkSave.run(async () => {
      const origins = apiAllowedOrigins.split(',').map((entry) => entry.trim()).filter(Boolean);
      await apiPost('/api/settings', {
        api_port: apiPort,
        api_bind_address: apiBindAddress.trim() === '' ? null : apiBindAddress.trim(),
        api_allowed_origins: origins.length > 0 ? origins : null,
      });
      return 'Authenticated API network settings applied to the running listener.';
    }, 'Failed to save API network settings', STICKY);
  };

  const handleApiKeyClear = () => {
    if (portMissing()) return;
    return keySave.run(async () => {
      await apiPost('/api/settings', { api_key: '', api_port: apiPort });
      setGeneratedApiKey(null);
      setApiKeyConfigured(false);
      setApiKeyLast4('');
      return 'API key cleared. Any saved key changes apply immediately to a running API server; starting it requires an app restart.';
    }, 'Failed to clear API key', STICKY);
  };

  return (
    <SettingsSection id={id} title="Remote / Mobile Network Access">
      <div className="flex flex-col gap-3">
        <UrlRow url={lanUrl} onCopy={copyUrl} />
        <p className={HINT}>Access this dashboard from any device on your network</p>

        <UrlRow url={lanReadOnlyUrl} onCopy={copyUrl} className="mt-2" />
        <p className={HINT}>
          Read-only link — hides Control and Settings in the visitor's browser (safe to share with family)
        </p>

        <UrlRow url={miniPageUrl} onCopy={copyUrl} className="mt-2" />
        <p className={HINT}>
          Apple Watch / mini display — a tiny glance view.{' '}
          <HelpTip label="the mini display URL">
            Open this URL in a browser for a tiny glance view, or fetch /api/mini/status from a Shortcut; see
            INSTALL.md.
          </HelpTip>
        </p>
      </div>

      <div className="flex flex-col gap-3 pt-3 border-t border-bg-elevated">
        <HeadingWithHelp
          as="h3"
          className="text-text-primary text-sm font-semibold"
          title="Authenticated API"
          help={
            <>
              External integrations (e.g. SolarWatch) use a separate API port with Bearer-token authentication,
              not the dashboard port above. GET /api/snapshot and GET /api/control/status are read-only.
              Battery Quick Actions require the permission below. Starting this server or changing its port requires a
              restart. These settings can only be changed from this machine.
            </>
          }
        />
        <p className={HINT}>A separate, key-protected port for integrations such as SolarWatch.</p>
        <p className={HINT}>
          {apiKeyConfigured
            ? `Key configured${apiKeyLast4 ? ` (ends ${apiKeyLast4})` : ''}. Generating a new key replaces the old one immediately.`
            : 'No key configured — the authenticated API is off.'}
        </p>
        {generatedApiKey && (
          <div className="flex flex-col gap-1 bg-bg-elevated rounded-lg p-3">
            <span className="text-text-primary text-xs font-sans font-semibold">
              New API key — copy it now, it will not be shown again:
            </span>
            <div className="flex items-center gap-3">
              <code className="text-accent text-sm font-mono flex-1 min-w-0 break-all select-all">{generatedApiKey}</code>
              <button
                onClick={() => { void navigator.clipboard.writeText(generatedApiKey); }}
                className="bg-bg-base text-text-primary font-sans text-sm px-4 py-2 rounded-lg hover:opacity-90 transition-opacity shrink-0"
              >Copy</button>
            </div>
          </div>
        )}
        <label className="flex flex-col gap-1">
          <span className={HINT}>Port</span>
          <input
            type="number"
            value={apiPort || ''}
            onChange={(e) => setApiPort(e.target.value === '' ? '' : Number(e.target.value))}
            placeholder="e.g. 7338"
            className={`${INPUT} w-32`}
          />
        </label>
        {apiKeyConfigured && apiBindAddress.trim() === '' && (
          <p className="text-amber-300 text-xs font-sans">
            Accepting connections on every network interface.{' '}
            <HelpTip label="the listen address">
              This server currently accepts connections on every network interface. Set a listen
              address under Advanced (127.0.0.1 keeps it local-only) if you only need machine-local
              or VPN/proxy access.
            </HelpTip>
          </p>
        )}
        <AdvancedSettings>
          <label className="flex flex-col gap-1">
            <span className={HINT}>Listen Address</span>
            <input
              type="text"
              value={apiBindAddress}
              onChange={(e) => setApiBindAddress(e.target.value)}
              placeholder="127.0.0.1 (local only) — blank = all interfaces"
              className={INPUT}
            />
          </label>
          <label className="flex flex-col gap-1">
            <span className={HINT}>Allowed Browser Origins (CORS, Comma-Separated)</span>
            <input
              type="text"
              value={apiAllowedOrigins}
              onChange={(e) => setApiAllowedOrigins(e.target.value)}
              placeholder="https://dashboard.example.com — blank = no browser access"
              className={INPUT}
            />
          </label>
          <button onClick={() => void handleApiNetworkSave()} disabled={networkSave.busy} className={PRIMARY_BUTTON}>
            {networkSave.busy ? 'Applying…' : 'Apply Network Settings'}
          </button>
        </AdvancedSettings>
        <div className="flex items-center justify-between gap-3">
          <span className="text-text-primary text-sm font-sans">Allow Battery Control Through the Authenticated API</span>
          <Toggle
            checked={apiControlEnabled}
            onChange={(v) => void setApiControlEnabled(v)}
            ariaLabel="Allow Battery Control Through the Authenticated API"
          />
        </div>
        <p className={HINT}>
          Lets anyone with the key Force Charge or Force Discharge.{' '}
          <HelpTip label="battery control through the API">
            Off by default and applied immediately when toggled. When enabled, anyone with this API key can use Force
            Charge, Force Discharge and their Stop actions. Turning it off does not stop an action already accepted.
          </HelpTip>
        </p>
        <div className="flex items-center gap-3">
          <button onClick={() => void handleApiKeyGenerate()} disabled={keySave.busy} className={PRIMARY_BUTTON}>
            {keySave.busy ? 'Generating…' : apiKeyConfigured ? 'Generate New Key' : 'Generate API Key'}
          </button>
          {apiKeyConfigured && (
            <button
              onClick={() => void handleApiKeyClear()}
              disabled={keySave.busy}
              className="self-start text-red-300 text-sm px-2 py-2 hover:text-red-200 transition-colors disabled:opacity-50"
            >Clear Saved Key</button>
          )}
        </div>
      </div>

      {clients.length > 0 && (
        <div className="flex flex-col gap-1.5">
          <span className={HINT}>Connected Clients ({clients.length})</span>
          {clients.map((addr, i) => {
            const ip = addr.replace(/:.*$/, '');
            const isLocal = ip === '127.0.0.1' || ip === '::1' || ip === lanIp;
            return (
              <div key={i} className="bg-bg-elevated rounded-lg px-3 py-2 flex items-center justify-between">
                <span className="text-text-primary text-sm font-mono">{addr}</span>
                {isLocal && <span className={HINT}>This Device</span>}
              </div>
            );
          })}
        </div>
      )}
    </SettingsSection>
  );
}
